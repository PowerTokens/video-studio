STRINGS = {'zh': ZH, 'en': EN}
_current = None


def windows_ui_language():
    """The Windows display language as a LANGID (e.g. 0x0804 zh-CN, 0x0409 en-US), or None."""
    if os.name != 'nt':
        return None
    try:
        import ctypes
        return int(ctypes.windll.kernel32.GetUserDefaultUILanguage())
    except Exception:
        return None


def system_language():
    """'zh' when the Windows display language (or the POSIX locale) is Chinese, else 'en'."""
    langid = windows_ui_language()
    if langid is not None:
        # Primary language ID 0x04 = Chinese (Simplified and Traditional).
        return 'zh' if langid & 0x3FF == 0x04 else 'en'
    for name in ('LC_ALL', 'LC_MESSAGES', 'LANG', 'LANGUAGE'):
        value = os.environ.get(name)
        if value:
            return 'zh' if value.lower().startswith('zh') else 'en'
    return 'en'


def load_settings():
    try:
        data = json.loads(SETTINGS_PATH.read_text(encoding='utf-8'))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def saved_language():
    value = load_settings().get('language')
    return value if value in LANGUAGES else None


def save_language(lang):
    """Persist the choice in settings.json next to the task records; other settings are kept."""
    if lang not in LANGUAGES:
        raise ValueError(lang)
    data = load_settings()
    data['language'] = lang
    SETTINGS_PATH.parent.mkdir(parents=True, exist_ok=True)
    temp = SETTINGS_PATH.with_name(SETTINGS_PATH.name + '.tmp')
    temp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    os.replace(temp, SETTINGS_PATH)


def get_language():
    global _current
    if _current is None:
        _current = saved_language() or system_language()
    return _current


def set_language(lang, persist=False):
    global _current
    if lang not in LANGUAGES:
        raise ValueError(lang)
    _current = lang
    if persist:
        save_language(lang)


def is_zh():
    return get_language() == 'zh'


def t(key, *args, count=None):
    """Look up key in the current language (falls back to Chinese), then apply % args."""
    value = STRINGS[get_language()].get(key)
    if value is None:
        value = ZH[key]
    if isinstance(value, tuple) and count is not None:
        value = value[0] if count == 1 else value[1]
    return value % args if args else value
